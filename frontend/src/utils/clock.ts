import { ref } from "vue";

// Единый реактивный «тикающий» таймер на всё приложение: один setInterval,
// обновляет now раз в секунду. Нужен, чтобы time-based computed'ы (например
// подсветка недавно изменённых файлов) пересчитывались по ходу времени, а не
// только при смене своих обычных реактивных зависимостей.
export const now = ref<number>(Date.now());

setInterval(() => {
  now.value = Date.now();
}, 1000);
